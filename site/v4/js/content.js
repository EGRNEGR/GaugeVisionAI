  var NBSP = ' ';
  var UNIT = new RegExp('(\\d) (?=(?:%|мин|мс|с|ч|МПа|кПа|бар|₽|тыс\\.|млн|шт\\.|лет|из|приборов|сообщений|°C|объектов|задач)(?![\\wа-яё]))', 'g');
